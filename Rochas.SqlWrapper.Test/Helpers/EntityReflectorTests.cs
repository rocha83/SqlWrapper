        #region GetPropertiesValueList

        [Fact]
        public void GetPropertiesValueList_AddAction_ExcludesAutoGeneratedNonGuid()
        {
            var entity = new SampleEntity { Name = "test" };
            var props = Helpers.EntityReflector.GetEntityProperties(typeof(SampleEntity));

            var list = Helpers.EntityReflector.GetPropertiesValueList(entity, typeof(SampleEntity), props, PersistenceAction.Add);

            Assert.NotNull(list);
            Assert.False(list.ContainsKey("Id"), "AutoGenerated non-Guid key should be excluded on Add");
            Assert.True(list.ContainsKey("Name"));
        }

        [Fact]
        public void GetPropertiesValueList_QueryAction_IncludesTableName()
