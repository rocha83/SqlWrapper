        #region SetFilterPrimaryKey / FK setters

        [Fact]
        public void SetFilterPrimaryKey_MovesKeyToFilterEntity()
        {
            var entity = new SampleEntity { Id = 99 };
            var filter = new SampleEntity();
            var props = Helpers.EntityReflector.GetEntityProperties(typeof(SampleEntity));

            Helpers.EntityReflector.SetFilterPrimaryKey(entity, props, filter);

            Assert.Equal(99, filter.Id);
            Assert.Equal(0, entity.Id);
        }

        [Fact]
        public void SetChildForeignKeyValue_WithParentKey_SetsChildForeignKey()
        {
            var parent = new SampleEntity { Id = 7 };
            var child = new SampleManyForeignEntity();
            var parentProps = Helpers.EntityReflector.GetEntityProperties(typeof(SampleEntity));
            var childProps = Helpers.EntityReflector.GetEntityProperties(typeof(SampleManyForeignEntity));

            var result = Helpers.EntityReflector.SetChildForeignKeyValue(parent, parentProps, child, childProps, "ParentId");

            Assert.True(result);
            Assert.Equal(7, child.ParentId);
        }

        [Fact]
        public void SetChildForeignKeyValue_WithoutParentKey_ReturnsFalse()
        {
            var parent = new SampleEntity { Id = 0 };
            var child = new SampleManyForeignEntity();
            var parentProps = Helpers.EntityReflector.GetEntityProperties(typeof(SampleEntity));
            var childProps = Helpers.EntityReflector.GetEntityProperties(typeof(SampleManyForeignEntity));

            var result = Helpers.EntityReflector.SetChildForeignKeyValue(parent, parentProps, child, childProps, "ParentId");

            Assert.False(result);
        }

        [Fact]
        public void SetParentForeignKeyValue_WithForeignKey_SetsChildKey()
        {
            var parent = new SampleEntity { ParentId = 11 };
            var child = new SampleManyForeignEntity();
            var parentProps = Helpers.EntityReflector.GetEntityProperties(typeof(SampleEntity));
            var childProps = Helpers.EntityReflector.GetEntityProperties(typeof(SampleManyForeignEntity));

            var result = Helpers.EntityReflector.SetParentForeignKeyValue(parent, parentProps, child, childProps, "ParentId");

            Assert.True(result);
            Assert.Equal(11, child.Id);
        }

        [Fact]
        public void SetEntityForeignKey_CopiesParentKeyToChildKey()
        {
            var parent = new SampleEntity { Id = 25 };
            var child = new SampleManyForeignEntity();

            Helpers.EntityReflector.SetEntityForeignKey(parent, child);

            Assert.Equal(25, child.Id);
        }

        [Fact]
        public void MatchKeys_EqualKeys_ReturnsTrue()
        {
            var entity1 = new SampleEntity { Id = 5 };
